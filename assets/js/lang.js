function getLang(){
  const current = localStorage.getItem('monechai_lang');
  if(current !== null) return current;
  const legacyKey = ['mone','chi'].join('')+'_lang';
  const legacy = localStorage.getItem(legacyKey);
  if(legacy !== null){ localStorage.setItem('monechai_lang', legacy); localStorage.removeItem(legacyKey); }
  return legacy || 'en';
}
